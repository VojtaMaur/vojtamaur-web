HERE = Path(__file__).resolve().parent
VERSION = "1.1.1"


def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


def atomic_bytes(path, data):
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("wb") as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)


def atomic_json(path, value):
    atomic_bytes(path, canonical(value) + b"\n")


@contextmanager
def edition_lock(folder):
    """OS locks release after crashes; a stale lock file never blocks resume."""
    with (folder / ".generation.lock").open("a+b") as stream:
        if stream.tell() == 0:
            stream.write(b"0")
            stream.flush()
        stream.seek(0)
        try:
            if os.name == "nt":
                import msvcrt
                msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise ValueError("This edition is already being generated by another process.") from exc
        try:
            yield
        finally:
            stream.seek(0)
            if os.name == "nt":
                import msvcrt
                msvcrt.locking(stream.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                import fcntl
                fcntl.flock(stream, fcntl.LOCK_UN)


def positive(value):
    number = int(value)
    if number < 1:
        raise argparse.ArgumentTypeError("Must be positive.")
    return number


def nonnegative(value):
    number = int(value)
    if number < 0:
        raise argparse.ArgumentTypeError("Must be nonnegative.")
    return number


def finite_nonnegative(value):
    number = float(value)
    if not math.isfinite(number) or number < 0:
        raise argparse.ArgumentTypeError("Must be finite and nonnegative.")
    return number


def arguments(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", action="version", version=VERSION)
    parser.add_argument("--project-root", type=Path, default=HERE.parents[1])
    parser.add_argument("--input", default="dist/ALL_POSTS.txt", help="Exact bytes archived; relative to project root.")
    parser.add_argument("--output-dir", default="exports", help="Parent of a new edition, under exports/.")
    parser.add_argument("--timestamp", help="YYYY-MM-DD_HH-MM-SS-ffffff; respects VOJTAMAUR_EXPORT_TIMESTAMP.")
    parser.add_argument("--resume", type=Path, help="Existing edition directory; --count adds this many memes.")
    amount = parser.add_mutually_exclusive_group()
    amount.add_argument("--count", type=positive, help="Default: 115%% of source symbols plus 8 per block.")
    amount.add_argument("--continuous", action="store_true", help="Run until Ctrl+C or RFC symbol-ID exhaustion.")
    parser.add_argument("--seed", help="Reproduce the same edition with unchanged inputs/settings; default: random.")
    parser.add_argument("--start-index", type=nonnegative, default=0, help="Start a new edition at a deterministic packet index.")
    parser.add_argument("--symbol-size", type=positive, default=512, help="Bytes per QR fountain symbol, 64..1024 (default: 512).")
    parser.add_argument("--rat-weight", type=finite_nonnegative, default=1.25, help="Relative weight of kurt-godel-rat.jpg (default: 1.25; other images: 1).")
    parser.add_argument("--max-text-chars", type=positive, default=120)
    parser.add_argument("--language", "--lang", type=str.lower, choices=("en", "cs", "en+cs"), default="en",
                        help="Caption and footer language: EN (default), CS or EN+CS. QR always archives the complete input TXT.")
    parser.add_argument("--width", type=positive, default=1080)
    parser.add_argument("--image-height", type=positive, default=810)
    parser.add_argument("--qr-scale", type=positive, default=4, help="Integer pixels/module, minimum 4.")
    parser.add_argument("--ecc", choices=("M", "Q", "H"), default="M")
    parser.add_argument("--font", help="Bold TrueType font; default: Impact or DejaVu Sans Bold.")
    parser.add_argument("--verify-qr", action="store_true", help="Scan every finished PNG using optional zxing-cpp.")
    parser.add_argument("--interval", type=finite_nonnegative, default=0, help="Seconds between memes.")
    args = parser.parse_args(argv)
    if not 64 <= args.symbol_size <= 1024:
        parser.error("--symbol-size must be 64..1024")
    if args.rat_weight <= 0 or args.qr_scale < 4 or args.width < 512 or args.image_height < 320:
        parser.error("Need positive --rat-weight, --qr-scale >=4, --width >=512 and --image-height >=320")
    if not 20 <= args.max_text_chars <= 240:
        parser.error("--max-text-chars must be 20..240")
    # Edition options must never be silently ignored when resuming.
    given = sys.argv[1:] if argv is None else argv
    immutable = ("--input", "--timestamp", "--seed", "--start-index", "--symbol-size", "--rat-weight",
                 "--max-text-chars", "--language", "--lang", "--width", "--image-height", "--qr-scale", "--ecc", "--output-dir")
    if args.resume and any(token.split("=", 1)[0] in immutable for token in given):
        parser.error("--resume uses the frozen edition settings; only count/continuous/interval/verify-qr/font may change")
    return args


def resolve(root, path):
    path = Path(path).expanduser()
    return (path if path.is_absolute() else root / path).resolve()


def naming(root):
    path = root / "scripts" / "export_naming.py"
    spec = importlib.util.spec_from_file_location("meme_export_naming", path)
    if not spec or not spec.loader:
        raise ValueError("Missing project scripts/export_naming.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def copy_tools(folder):
    target = folder / "decoder"
    target.mkdir()
    # Ship usable sources and the small prebuilt codec, never installations/build caches.
    for source in HERE.iterdir():
        if source.is_file() and source.suffix in {".py", ".mjs", ".wasm", ".md", ".txt"}:
            shutil.copy2(source, target / source.name)
    adapter = HERE / "wasm-adapter"
    if adapter.is_dir():
        for source in adapter.rglob("*"):
            relative = source.relative_to(adapter)
            if source.is_file() and not any(part in {"target", "node_modules", ".git"} for part in relative.parts):
                output = target / "wasm-adapter" / relative
                output.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, output)


def create_edition(args, root, backend):
    source = resolve(root, args.input)
    raw = source.read_bytes()
    if not raw or len(raw) > 64 * 1024 * 1024:
        raise ValueError("Archive input must contain 1..67108864 bytes.")
    raw.decode("utf-8-sig")  # ALL_POSTS is a UTF-8 text archive; preserve its exact bytes.
    archive = make_object(raw)
    config = backend.request("init_encoder", data=base64.b64encode(archive).decode("ascii"), symbol_size=args.symbol_size)
    catalog = build_catalog(root, args.max_text_chars, args.language)
    font = Path(find_font(args.font))
    seed = args.seed if args.seed is not None else secrets.token_hex(16)
    settings = dict(width=args.width, photo_height=args.image_height, qr_scale=args.qr_scale, ecc=args.ecc,
                    language=args.language,
                    recovery=dict(minimum=sum(config["source_counts"]),
                                  recommended=sum(config["source_counts"]) + 2 * config["block_count"],
                                  blocks=config["block_count"]))
    descriptor = dict(version=VERSION, seed=seed, archive_sha256=hashlib.sha256(archive).hexdigest(),
                      catalog_sha256=hashlib.sha256(canonical(catalog)).hexdigest(),
                      font_sha256=sha256_file(font), settings=settings, rat_weight=args.rat_weight,
                      oti=config["oti"])
    edition = hashlib.sha256(canonical(descriptor)).digest()[:16].hex()
    helper = naming(root)
    stamp = helper.validate_timestamp(args.timestamp) if args.timestamp else helper.new_timestamp()
    parent = resolve(root, args.output_dir)
    if not parent.is_relative_to((root / "exports").resolve()):
        raise ValueError("Output must be under the project's exports/ directory.")
    parent.mkdir(parents=True, exist_ok=True)
    folder = parent / f"vojtamaur-web-export-meme-archive-{stamp}"
    folder.mkdir(exist_ok=False)
    (folder / "memes").mkdir()
    atomic_bytes(folder / "archive.rq", archive)
    atomic_json(folder / "catalog.json", catalog)
    manifest = dict(format="meme-archive", version=VERSION, timestamp=stamp, edition=edition,
                    recipe=descriptor, font_path=str(font), input_path=str(source), input_bytes=len(raw),
                    input_sha256=hashlib.sha256(raw).hexdigest(), source_counts=config["source_counts"],
                    symbol_size=config["symbol_size"], block_count=config["block_count"], start_index=args.start_index,
                    runtime=dict(python=sys.version.split()[0]))
    atomic_json(folder / "manifest.json", manifest)
    copy_tools(folder)
    (folder / "README.txt").write_text(
        "MEME ARCHIVE / Vojta Maur / https://vojtamaur.cz/\n"
        f"Edition: {edition}\nSeed: {seed}\nCaption/footer language: {args.language.upper()}\n"
        "Decode from PNG/JPEG pixels (no manifest or sidecars required):\n"
        "  python decoder/decode.py memes --output ALL_POSTS.recovered.txt\n"
        "Install Python dependencies from decoder/requirements-decode.txt; Node.js 18+ is also required.\n"
        "See decoder/README.md and decoder/FORMAT.md for installation, resume and RFC references.\n"
        "Keep original PNGs. Resizing/JPEG/social sites may destroy QR readability.\n"
        "archive.rq and catalog.json are frozen inputs for resume; memes.jsonl records provenance.\n",
        encoding="utf-8")
    return folder, manifest, catalog


def resume_edition(args, root, backend):
    folder = resolve(root, args.resume)
    if not folder.is_relative_to((root / "exports").resolve()):
        raise ValueError("Resume edition must be under the project's exports/ directory.")
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("format") != "meme-archive" or manifest.get("version") not in {"1.0.0", "1.1.0", VERSION}:
        raise ValueError("Unsupported edition manifest.")
    descriptor = manifest["recipe"]
    if hashlib.sha256(canonical(descriptor)).digest()[:16].hex() != manifest["edition"]:
        raise ValueError("Edition recipe hash mismatch.")
    archive = (folder / "archive.rq").read_bytes()
    if hashlib.sha256(archive).hexdigest() != descriptor["archive_sha256"]:
        raise ValueError("Frozen archive.rq hash mismatch.")
    catalog = json.loads((folder / "catalog.json").read_text(encoding="utf-8"))
    if hashlib.sha256(canonical(catalog)).hexdigest() != descriptor["catalog_sha256"]:
        raise ValueError("Frozen catalogue hash mismatch.")
    font = Path(find_font(args.font or manifest["font_path"]))
    if sha256_file(font) != descriptor["font_sha256"]:
        raise ValueError("Resume requires the same font bytes; supply --font with the original font.")
    manifest["font_path"] = str(font)
    config = backend.request("init_encoder", data=base64.b64encode(archive).decode("ascii"), symbol_size=manifest["symbol_size"])
    if config["oti"] != descriptor["oti"] or config["source_counts"] != manifest["source_counts"]:
        raise ValueError("Codec configuration differs from the frozen edition.")
    return folder, manifest, catalog


def recover_progress(folder, manifest):
    """The fsynced JSONL is the commit journal; an interrupted last PNG is regenerated."""
    index = manifest["start_index"]
    journal = folder / "memes.jsonl"
    if not journal.exists():
        return index
    committed = 0
    with journal.open("rb") as stream:
        for line in stream:
            if not line.endswith(b"\n"):
                break
            record = json.loads(line)
            expected = f"memes/{index + 1:08d}.png"
            if record["index"] != index or record["file"] != expected:
                raise ValueError("Edition journal has a gap or invalid path.")
            path = folder / expected
            if not path.is_file() or sha256_file(path) != record["sha256"]:
                raise ValueError(f"Committed meme missing or changed: {expected}")
            committed += len(line)
            index += 1
    if journal.stat().st_size != committed:
        # A crash may leave an incomplete final journal record. Preserve evidence.
        shutil.copy2(journal, journal.with_suffix(".interrupted.jsonl"))
        with journal.open("r+b") as stream:
            stream.truncate(committed)
    return index


def main(argv=None):
    args = arguments(argv)
    root = args.project_root.expanduser().resolve()
    import PIL.Image  # fail before creating an output edition
    import segno  # noqa: F401
    if args.verify_qr:
        import zxingcpp  # noqa: F401
    with Backend() as backend:
        folder, manifest, catalog = (resume_edition(args, root, backend) if args.resume
                                     else create_edition(args, root, backend))
        with edition_lock(folder):
            start = index = recover_progress(folder, manifest)
            count = args.count or sum(math.ceil(n * 1.15) + 8 for n in manifest["source_counts"])
            print(f"Edition {manifest['edition']}\nOutput: {folder}\n"
                  f"Source symbols: {sum(manifest['source_counts'])}; next meme: {index + 1}; "
                  + ("continuous (Ctrl+C stops safely)" if args.continuous else f"generating {count}"), flush=True)
            settings = dict(manifest["recipe"]["settings"], font=manifest["font_path"], edition=manifest["edition"])
            try:
                with (folder / "memes.jsonl").open("ab") as journal:
                    while args.continuous or index - start < count:
                        response = backend.request("packet", index=index)
                        rq_packet = base64.b64decode(response["packet"], validate=True)
                        payload = wrap_packet(bytes.fromhex(manifest["edition"]),
                                              base64.b64decode(manifest["recipe"]["oti"], validate=True), rq_packet)
                        choice = choose_meme(catalog, manifest["recipe"]["seed"], index, manifest["recipe"]["rat_weight"])
                        relative = f"memes/{index + 1:08d}.png"
                        destination = folder / relative
                        temporary = destination.with_suffix(".png.part")
                        geometry = render_meme(root, choice, payload, temporary, dict(settings, index=index))
                        if args.verify_qr and payload not in scan_packets(temporary):
                            raise ValueError(f"QR read-back failed for meme {index + 1}")
                        os.replace(temporary, destination)
                        record = dict(index=index, file=relative, sha256=sha256_file(destination), choice=choice,
                                      rq_payload_id=rq_packet[:4].hex(), qr_verified=args.verify_qr, render=geometry)
                        journal.write(canonical(record) + b"\n")
                        journal.flush()
                        os.fsync(journal.fileno())
                        index += 1
                        atomic_json(folder / "state.json", dict(next_index=index, edition=manifest["edition"]))
                        if index - start == 1 or (index - start) % 10 == 0:
                            print(f"Generated {index - start}; next index {index}", flush=True)
                        if args.interval:
                            time.sleep(args.interval)
            except KeyboardInterrupt:
                print("Stopped; resume continues after the last committed meme.", flush=True)
            print(f"Finished: {index - start} new memes in {folder}", flush=True)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ImportError, FileNotFoundError) as exc:
        print(f"Missing input or optional dependency: {exc}\nSee scripts/meme-archive/README.md.", file=sys.stderr)
        raise SystemExit(3)
    except (ValueError, RuntimeError, OSError, KeyError) as exc:
        print(f"Meme archive error: {exc}", file=sys.stderr)
        raise SystemExit(1)
