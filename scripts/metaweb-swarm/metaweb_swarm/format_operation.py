"""Native-format minimums, not provider connectors or automatic scope approval."""
from pathlib import PurePosixPath
import re
import xml.etree.ElementTree as ET


def contract(idea,payload):
    claim=' '.join(str(idea.get(k,'')) for k in ('title','mechanism','mechanism_key'))
    if not re.search(r'\bRSS\b',claim,re.I):return None
    return {'kind':'RSS_2_POINTER','operation':'Serialize a real RSS 2.0 XML channel/item, save the feed, then independently parse it and restore the expected pointer fields.',
        'expected':{'title':PurePosixPath(payload.get('export') or payload['path']).name,
                    'guid':'urn:sha256:'+payload['sha256'],'link':'https://vojtamaur.cz/'},
        'consumer':'Expose read_pointer(path) in captured Python implementation; parse saved XML and validate required fields. Return title/guid/link. Reject malformed XML and a well-formed item missing guid.',
        'negative_case':'Delete guid from a saved valid feed; the consumer must reject that feed. A changed hash string or missing workspace folder is not this test.',
        'scope':'Local RSS pointer serialization only. No public publication, independent custody, podcast playback or recovery of the original EPUB is established.',
        'minimum_only':'Host independently parses generated bytes and compares fields; auditor still tests consumer behavior and judges coverage.'}


def read_pointer(body):
    """Host-owned XML reader; no model code is imported or executed on the host."""
    if len(body)>2_000_000 or b'\x00' in body or b'<!DOCTYPE' in body.upper() or b'<!ENTITY' in body.upper():
        raise ValueError('RSS must be bounded XML without DTD/entities')
    try:text=body.decode('utf-8-sig')
    except UnicodeError as error:raise ValueError('The local RSS contract uses UTF-8 XML') from error
    root=ET.fromstring(text)
    if root.tag!='rss' or root.get('version')!='2.0':raise ValueError('Expected RSS 2.0 XML')
    channel=root.find('channel')
    if channel is None:raise ValueError('RSS channel missing')
    for key in ('title','link','description'):
        if not (channel.findtext(key) or '').strip():raise ValueError('RSS channel '+key+' missing')
    items=channel.findall('item')
    if len(items)!=1:raise ValueError('The local contract needs exactly one pointer item')
    result={key:(items[0].findtext(key) or '').strip() for key in ('title','guid','link')}
    if not all(result.values()):raise ValueError('RSS item title/guid/link missing')
    return result


def validate(idea,payload,paths,reader):
    specification=contract(idea,payload)
    if not specification:return None
    errors=[]
    for path in paths:
        if PurePosixPath(path).suffix.lower() not in {'.rss','.xml'}:continue
        try:
            actual=read_pointer(reader(path))
            if actual!=specification['expected']:raise ValueError('Pointer differs from contract: '+repr(actual))
            return {'passed':True,'kind':specification['kind'],'path':path,'expected':actual,
                    'meaning':'Native RSS bytes independently parsed; consumer rejection and broader scope still require review.'}
        except (ValueError,ET.ParseError) as error:errors.append({'path':path,'error':str(error)[:1500]})
    return {'passed':False,'status':'DEFERRED','reason':'NATIVE_RSS_OPERATION_REQUIRED','errors':errors,
            'expected':specification,'next_action':'Generate and declare a .rss or .xml output with the expected item fields. Implement/read back actual RSS using read_pointer(path); JSON/hash helpers do not satisfy this operation.'}
